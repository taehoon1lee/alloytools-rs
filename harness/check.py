"""Compare alloy-rs (Rust) against the Java golden outputs.

THIS IS THE ONLY SCORE THAT MATTERS. Do not edit this file or the goldens from the loop.

Usage (from repo root):
  python harness/check.py                 # build release + run whole corpus, print scoreboard
  python harness/check.py --quick         # small smoke subset (harness/quick.txt), ~seconds
  python harness/check.py --filter puzzles      # only ids containing 'puzzles'
  python harness/check.py --id models/puzzles/money --verbose   # detailed diff for one model
  python harness/check.py --failing       # only models that were not fully passing in the last run
  python harness/check.py --perf          # sequential run (-j 1) for trustworthy timings
  python harness/check.py --count         # compare solution counts (symmetry=0) vs harness/golden_count
  python harness/check.py --gate          # exit 1 if anything that passed in best.json now fails
  python harness/check.py --update-best   # record current passes as the new baseline (refused on regression)

Levels (each is a superset requirement of the previous one):
  parse    file-level status equals Java (ok / syntax_error / type_error / error)
  commands command list equals Java (label, kind, expects, scope string, overall, bitwidth, maxseq, prefix)
  verdict  per command: SAT/UNSAT (or ERROR) equals Java
  perf     verdict ok AND rust_total_ms <= 1.10 * java_total_ms + 20
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime
from pathlib import Path

from common import (GOLDEN_COUNT_DIR, GOLDEN_DIR, HARNESS, RESULTS_DIR, ROOT, RUST_BIN, golden_name, last_json_line,
                    load_corpus, load_json, run_proc)

HEADER_FIELDS = ["label", "kind", "expects", "scope", "overall", "bitwidth", "maxseq", "minprefix", "maxprefix"]
PERF_FACTOR, PERF_SLACK_MS = 1.10, 20.0
LATEST = RESULTS_DIR / "latest.json"
BEST = RESULTS_DIR / "best.json"
HISTORY = RESULTS_DIR / "history.csv"
QUICK = HARNESS / "quick.txt"


# ----------------------------------------------------------------------------- running

def build() -> bool:
    env = dict(os.environ)
    cargo_bin = Path.home() / ".cargo" / "bin"
    env["PATH"] = str(cargo_bin) + os.pathsep + env.get("PATH", "")
    r = subprocess.run(["cargo", "build", "--release", "--bin", "alloy-rs"], cwd=str(ROOT), env=env,
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        lines = [l for l in r.stderr.splitlines() if l.strip()]
        errs = [l for l in lines if l.startswith("error")]
        print("BUILD FAILED (cargo build --release). First errors:")
        print("\n".join(lines[-40:]))
        print(f"... {len(errs)} error line(s). Fix the build first.")
        return False
    return True


def rust_cmd(path, cid, extra):
    return [str(RUST_BIN), "exec", "--json", "--file", path, "--display-name", cid] + extra


def crash_doc(cid, rc, out, err, what):
    tail = (err or out or "").strip().splitlines()[-6:]
    return {"status": "crash", "error": {"kind": "crash", "msg": f"{what} rc={rc}: " + " | ".join(tail)[-400:]},
            "commands": []}


def run_rust_entry(entry, golden, count_mode):
    cid, path = entry["id"], entry["path"]
    rc, out, err, _ = run_proc(rust_cmd(path, cid, ["--no-solve"]), timeout_s=60)
    if rc is None:
        return {"status": "timeout", "error": {"kind": "timeout", "msg": "parse took > 60s"}, "commands": []}
    doc = last_json_line(out)
    if doc is None:
        return crash_doc(cid, rc, out, err, "no JSON from --no-solve")
    if doc.get("status") != "ok" or golden.get("status") != "ok":
        doc["commands"] = []
        return doc
    rust_n = doc.get("command_count", 0)
    results = []
    for jc in golden.get("commands", []):
        i = jc["index"]
        if i >= rust_n:
            continue
        if jc.get("status") not in ("SAT", "UNSAT", "ERROR"):
            continue  # Java timed out: not scored
        jt = float(jc.get("total_ms") or 0) + float(jc.get("count_ms") or 0)
        tmo = int(min(60000, max(3000, 5 * jt + 2000)))
        extra = ["--command", str(i), "--timeout-ms", str(tmo)]
        if count_mode:
            extra += ["--symmetry", "0", "--count", str(golden.get("_count_cap", 100)), "--no-instance"]
        rc, out, err, el = run_proc(rust_cmd(path, cid, extra), timeout_s=tmo / 1000 + 15)
        cdoc = last_json_line(out)
        if rc is None or cdoc is None or not cdoc.get("commands"):
            st = "TIMEOUT" if rc is None else "CRASH"
            tail = " | ".join((err or "").strip().splitlines()[-4:])[-300:]
            results.append({"index": i, "status": st, "error": {"kind": st.lower(), "msg": f"rc={rc} {tail}"}})
        else:
            results.append(cdoc["commands"][0])
    doc["commands"] = results
    return doc


# ----------------------------------------------------------------------------- scoring

def score_entry(cid, golden, rust, count_mode):
    rec = {"id": cid, "java_status": golden.get("status"), "rust_status": rust.get("status"),
           "rust_error": (rust.get("error") or {}).get("msg"), "java_error": (golden.get("error") or {}).get("msg"),
           "parse_ok": golden.get("status") == rust.get("status"), "commands_ok": None, "cmds": []}
    if golden.get("status") == "ok" and not rec["parse_ok"]:
        # Java parsed it; every Java-decided command counts as a failure so the denominator stays fixed
        for jc in golden.get("commands", []):
            scored = jc.get("status") in ("SAT", "UNSAT", "ERROR")
            rec["cmds"].append({"index": jc["index"], "label": jc.get("label"), "java": jc.get("status"),
                                "rust": f"file:{rust.get('status')}", "java_ms": jc.get("total_ms"), "rust_ms": None,
                                "scored": scored, "verdict_ok": False, "perf_ok": False, "file_failed": True})
        return rec
    if golden.get("status") != "ok" or not rec["parse_ok"]:
        if rec["parse_ok"]:
            rec["commands_ok"] = True
            je, re_ = golden.get("error") or {}, rust.get("error") or {}
            rec["error_line_match"] = (je.get("line"), je.get("col")) == (re_.get("line"), re_.get("col"))
        return rec
    gcmds = golden.get("commands", [])
    if rust.get("command_count") != golden.get("command_count"):
        rec["commands_ok"] = False
        rec["commands_diff"] = f"command_count java={golden.get('command_count')} rust={rust.get('command_count')}"
    else:
        rec["commands_ok"] = True
    rmap = {c["index"]: c for c in rust.get("commands", [])}
    for jc in gcmds:
        i = jc["index"]
        rc_ = rmap.get(i)
        c = {"index": i, "label": jc.get("label"), "java": jc.get("status"), "rust": rc_.get("status") if rc_ else None,
             "java_ms": jc.get("total_ms"), "rust_ms": rc_.get("total_ms") if rc_ else None}
        if rc_ is not None:
            diffs = [f"{f}: java={jc.get(f)!r} rust={rc_.get(f)!r}" for f in HEADER_FIELDS if jc.get(f) != rc_.get(f)]
            if diffs and "index" in rc_ and rc_.get("status") not in ("TIMEOUT", "CRASH"):
                c["header_diff"] = diffs
                rec["commands_ok"] = False
                rec.setdefault("commands_diff", "; ".join(diffs[:3]))
            if rc_.get("error"):
                c["rust_error"] = (rc_["error"] or {}).get("msg")
        if jc.get("status") not in ("SAT", "UNSAT", "ERROR"):
            c["scored"] = False
            rec["cmds"].append(c)
            continue
        c["scored"] = True
        if count_mode:
            c["java_count"], c["rust_count"] = jc.get("count"), (rc_ or {}).get("count")
            c["verdict_ok"] = (rc_ is not None and jc.get("count") == rc_.get("count")
                               and jc.get("count_capped") == rc_.get("count_capped"))
            c["perf_ok"] = c["verdict_ok"]
        else:
            c["verdict_ok"] = rc_ is not None and rc_.get("status") == jc.get("status")
            perf = False
            if c["verdict_ok"] and jc.get("status") in ("SAT", "UNSAT"):
                jm, rm = float(jc.get("total_ms") or 0), float(rc_.get("total_ms") or 1e18)
                perf = rm <= PERF_FACTOR * jm + PERF_SLACK_MS
                c["ratio"] = round(rm / max(jm, 0.001), 3)
            elif c["verdict_ok"]:
                perf = True  # matching ERROR
            c["perf_ok"] = perf
            js, rs = jc.get("stats") or {}, (rc_ or {}).get("stats") or {}
            if js and rs:
                c["primary_vars_match"] = js.get("primary_vars") == rs.get("primary_vars")
                c["java_stats"], c["rust_stats"] = js, rs
        rec["cmds"].append(c)
    return rec


def keysets(recs):
    s = {"parse": set(), "commands": set(), "verdict": set(), "perf": set()}
    for r in recs:
        if r["parse_ok"]:
            s["parse"].add(r["id"])
        if r["parse_ok"] and r["commands_ok"]:
            s["commands"].add(r["id"])
        for c in r["cmds"]:
            if c.get("scored"):
                k = f"{r['id']}#{c['index']}"
                if c.get("verdict_ok"):
                    s["verdict"].add(k)
                if c.get("perf_ok"):
                    s["perf"].add(k)
    return s


# ----------------------------------------------------------------------------- reporting

def git_rev():
    try:
        r = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=str(ROOT), capture_output=True, text=True)
        return r.stdout.strip() or "-"
    except Exception:
        return "-"


def fmt_fail(r, c=None):
    if c is None:
        if not r["parse_ok"]:
            return f"[parse]    {r['id']}: java={r['java_status']} rust={r['rust_status']}  {(r.get('rust_error') or '')[:150]}"
        return f"[commands] {r['id']}: {r.get('commands_diff', '')[:200]}"
    if not c.get("verdict_ok"):
        extra = f" count java={c.get('java_count')} rust={c.get('rust_count')}" if "java_count" in c else ""
        return (f"[verdict]  {r['id']}#{c['index']} {c['label']}: java={c['java']} rust={c['rust']}{extra}  "
                f"{(c.get('rust_error') or '')[:140]}")
    return (f"[perf]     {r['id']}#{c['index']} {c['label']}: java={c['java_ms']}ms rust={c['rust_ms']}ms "
            f"(x{c.get('ratio')})")


def print_verbose(rec, golden, rust):
    print(json.dumps({"java_file_status": golden.get("status"), "java_error": golden.get("error"),
                      "rust_file_status": rust.get("status"), "rust_error": rust.get("error")}, indent=1))
    rmap = {c["index"]: c for c in rust.get("commands", [])}
    for jc in golden.get("commands", []):
        rc_ = rmap.get(jc["index"], {})
        print(f"--- command #{jc['index']} {jc.get('label')}  ({jc.get('scope')})")
        for k in HEADER_FIELDS + ["status", "total_ms", "translate_ms", "solve_ms", "stats", "count", "error"]:
            jv, rv = jc.get(k), rc_.get(k)
            mark = "  " if jv == rv else "!="
            print(f"  {mark} {k:13s} java={json.dumps(jv)[:160]}  rust={json.dumps(rv)[:160]}")
        if jc.get("instance") and rc_.get("instance"):
            same = jc["instance"] == rc_["instance"]
            print(f"     instance      {'identical' if same else 'differs (OK if both satisfy the model; SAT solvers differ)'}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--filter")
    ap.add_argument("--id")
    ap.add_argument("--failing", action="store_true")
    ap.add_argument("--perf", action="store_true")
    ap.add_argument("--count", action="store_true")
    ap.add_argument("-j", type=int, default=None)
    ap.add_argument("--no-build", action="store_true")
    ap.add_argument("--top", type=int, default=20)
    ap.add_argument("--verbose", action="store_true")
    ap.add_argument("--gate", action="store_true")
    ap.add_argument("--update-best", action="store_true")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    gdir = GOLDEN_COUNT_DIR if a.count else GOLDEN_DIR
    corpus = [e for e in load_corpus() if (gdir / golden_name(e["id"])).exists()]
    if a.quick:
        q = [l.strip() for l in QUICK.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
        corpus = [e for e in corpus if e["id"] in q]
    if a.filter:
        corpus = [e for e in corpus if a.filter in e["id"]]
    if a.id:
        corpus = [e for e in corpus if e["id"] == a.id]
    if a.failing:
        prev = load_json(LATEST) or {}
        bad = {r["id"] for r in prev.get("records", []) if not r["parse_ok"] or not r["commands_ok"]
               or any(c.get("scored") and not c.get("perf_ok") for c in r["cmds"])}
        corpus = [e for e in corpus if e["id"] in bad] if prev else corpus
    if not corpus:
        print("no models selected (are goldens generated? see harness/README.md)")
        return 2
    goldens = {e["id"]: load_json(gdir / golden_name(e["id"])) for e in corpus}
    corpus = [e for e in corpus if goldens[e["id"]] and (goldens[e["id"]].get("error") or {}).get("kind") != "oracle_crash"]

    if not a.no_build and not build():
        return 2
    jobs = 1 if a.perf else (a.j or max(1, min(8, (os.cpu_count() or 2) // 2)))
    t0 = time.time()

    def job(e):
        g = goldens[e["id"]]
        r = run_rust_entry(e, g, a.count)
        return e["id"], r, score_entry(e["id"], g, r, a.count)

    with ThreadPoolExecutor(max_workers=jobs) as ex:
        out = list(ex.map(job, sorted(corpus, key=lambda e: e["lines"])))
    recs = [o[2] for o in out]
    elapsed = time.time() - t0

    if a.verbose:
        for cid, rust, rec in out:
            print(f"===== {cid}")
            print_verbose(rec, goldens[cid], rust)

    ks = keysets(recs)
    n_files = len(recs)
    n_ok_files = sum(1 for r in recs if r["java_status"] == "ok")
    n_scored = sum(1 for r in recs for c in r["cmds"] if c.get("scored"))
    n_unscored = sum(1 for r in recs for c in r["cmds"] if not c.get("scored"))
    jt = sum(float(c["java_ms"] or 0) for r in recs for c in r["cmds"] if c.get("verdict_ok") and c["java"] in ("SAT", "UNSAT"))
    rt = sum(float(c["rust_ms"] or 0) for r in recs for c in r["cmds"] if c.get("verdict_ok") and c["java"] in ("SAT", "UNSAT"))
    hist = {}
    for r in recs:
        if r["java_status"] == "ok" and r["rust_status"] != "ok":
            hist[f"file:{r['rust_status']}"] = hist.get(f"file:{r['rust_status']}", 0) + 1
        for c in r["cmds"]:
            if c.get("scored") and not c.get("file_failed"):
                hist[str(c["rust"])] = hist.get(str(c["rust"]), 0) + 1

    mode = "COUNT (symmetry=0)" if a.count else "VERDICT"
    print(f"=== alloy-rs vs java-alloy-6.2.0 [{mode}] {n_files} models, {n_scored} scored commands "
          f"({n_unscored} skipped: Java timeout)  [{elapsed:.1f}s, -j{jobs}] ===")
    print(f"parse    : {len(ks['parse']):4d}/{n_files}   file status matches Java")
    print(f"commands : {len(ks['commands']):4d}/{n_files}   command list matches Java")
    print(f"verdict  : {len(ks['verdict']):4d}/{n_scored}   {'count' if a.count else 'SAT/UNSAT/ERROR'} matches Java")
    if not a.count:
        print(f"perf     : {len(ks['perf']):4d}/{n_scored}   verdict ok AND rust <= {PERF_FACTOR}*java+{PERF_SLACK_MS:.0f}ms")
        if jt:
            print(f"time     : rust {rt / 1000:.2f}s vs java {jt / 1000:.2f}s over verdict-matching commands "
                  f"(x{rt / max(jt, 1e-9):.2f})")
    print(f"rust status histogram: {dict(sorted(hist.items(), key=lambda kv: -kv[1]))}")

    # failures in milestone order, smallest model first
    fails = []
    for r in recs:  # already sorted by size
        if not r["parse_ok"] or not r["commands_ok"]:
            fails.append((0 if not r["parse_ok"] else 1, fmt_fail(r)))
    for r in recs:
        for c in r["cmds"]:
            if c.get("scored") and not c.get("verdict_ok") and not c.get("file_failed"):
                fails.append((2, fmt_fail(r, c)))
    perf_fails = [(r, c) for r in recs for c in r["cmds"] if c.get("verdict_ok") and not c.get("perf_ok")]
    perf_fails.sort(key=lambda rc: -(rc[1].get("ratio") or 0))
    fails += [(3, fmt_fail(r, c)) for r, c in perf_fails]
    fails.sort(key=lambda x: x[0])
    if fails:
        print(f"--- top failures ({len(fails)} total; fix in this order) ---")
        for _, f in fails[:a.top]:
            print("  " + f)

    # regressions vs best
    best = load_json(BEST)
    evaluated = {r["id"] for r in recs}
    regress = []
    if best:
        for lvl in ("parse", "commands", "verdict"):
            for k in best.get(lvl, []):
                fid = k.split("#")[0]
                if fid in evaluated and k not in ks[lvl]:
                    regress.append(f"{lvl}:{k}")
    if regress:
        print(f"!!! REGRESSIONS vs best.json ({len(regress)}): " + ", ".join(regress[:15]))
    else:
        print("regressions vs best.json: none")

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    full_run = not (a.quick or a.filter or a.id or a.failing)
    if not a.count:
        if full_run or not LATEST.exists():
            LATEST.write_text(json.dumps({"time": datetime.now().isoformat(timespec="seconds"), "rev": git_rev(),
                                          "records": recs}, indent=1), encoding="utf-8")
        new_hist = not HISTORY.exists()
        with HISTORY.open("a", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            if new_hist:
                w.writerow(["time", "rev", "scope", "files", "parse", "commands", "scored", "verdict", "perf",
                            "rust_s", "java_s", "regressions"])
            scope = "full" if full_run else ("quick" if a.quick else "partial")
            w.writerow([datetime.now().isoformat(timespec="seconds"), git_rev(), scope, n_files, len(ks["parse"]),
                        len(ks["commands"]), n_scored, len(ks["verdict"]), len(ks["perf"]), round(rt / 1000, 3),
                        round(jt / 1000, 3), len(regress)])
    if a.update_best:
        if regress:
            print("refusing --update-best: there are regressions")
        else:
            merged = {lvl: sorted(set((best or {}).get(lvl, [])) | ks[lvl]) for lvl in ("parse", "commands", "verdict", "perf")}
            BEST.write_text(json.dumps(merged, indent=0), encoding="utf-8")
            print(f"best.json updated: " + ", ".join(f"{k}={len(v)}" for k, v in merged.items()))
    if a.gate and regress:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
