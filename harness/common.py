CP_SEP = ";" if os.name == "nt" else ":"


def golden_name(cid: str) -> str:
    return cid.replace("/", "__") + ".json"


def load_corpus() -> list[dict]:
    return json.loads(CORPUS_FILE.read_text(encoding="utf-8"))


def load_json(p: Path):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return None


def run_proc(cmd: list[str], timeout_s: float, cwd: Path = ROOT):
    """Run a process; returns (returncode|None on timeout, stdout, stderr, elapsed_s)."""
    import time

    t0 = time.perf_counter()
    try:
        p = subprocess.Popen(cmd, cwd=str(cwd), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                             stdin=subprocess.DEVNULL)
    except FileNotFoundError as e:
        return -999, "", str(e), 0.0
    try:
        out, err = p.communicate(timeout=timeout_s)
        rc = p.returncode
    except subprocess.TimeoutExpired:
        kill_tree(p)
        out, err = p.communicate()
        rc = None
    return rc, out.decode("utf-8", "replace"), err.decode("utf-8", "replace"), time.perf_counter() - t0


def kill_tree(p: subprocess.Popen):
    if os.name == "nt":
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(p.pid)], capture_output=True)
    else:
        p.kill()


def last_json_line(text: str):
    """The tools print exactly one JSON document; take the last line that parses."""
    for line in reversed(text.strip().splitlines()):
        line = line.strip()
        if line.startswith("{"):
            try:
                return json.loads(line)
            except Exception:
                continue
    return None


def eprint(*a):
    print(*a, file=sys.stderr, flush=True)
