import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HARNESS = ROOT / "harness"
REFERENCE = ROOT / "reference"
CORPUS_FILE = HARNESS / "corpus.json"
GOLDEN_DIR = HARNESS / "golden"           # verdict + timing + first instance (symmetry=20)
GOLDEN_COUNT_DIR = HARNESS / "golden_count"  # solution counts with symmetry=0
RESULTS_DIR = HARNESS / "results"
